#ifndef UNITTESTS_TESTSUPPORT_HPP
#define UNITTESTS_TESTSUPPORT_HPP
/**
 * @file TestSupport.hpp
 * @brief Shared helpers for the Catch2 unit-test suite.
 *
 * Everything here is header-inline so that a test file only has to include this header to get the
 * payload builders and the device readers it needs. The helpers are deliberately deterministic:
 * every random-looking byte comes from a fixed-seed generator, so a failing round-trip can be
 * reproduced exactly.
 */
#include <Elvavena/Io/ElvIoDevice.hpp>
#include <cstddef>
#include <cstdint>
#include <vector>

namespace UnitTests {

/**
 * @brief Builds a deterministic, poorly compressible payload.
 * @param size Number of bytes to produce.
 * @param seed Generator state to start from; the same seed always yields the same bytes.
 * @return Payload of exactly @p size bytes, generated by a linear congruential generator.
 * @note The data is intentionally incompressible-ish so that a codec is exercised on its
 *       "compressed output is larger than the input" path as well.
 */
inline std::vector<std::byte> makePattern(size_t size, std::uint32_t seed = 0x9E3779B9u)
{
	std::vector<std::byte> bytes(size);
	std::uint32_t state = seed;
	for (size_t index = 0; index < size; ++index) {
		state = state * 1664525u + 1013904223u;
		bytes[index] = static_cast<std::byte>((state >> 16) & 0xFFu);
	}
	return bytes;
}

/**
 * @brief Builds a highly compressible payload.
 * @param size Number of bytes to produce.
 * @return Payload of exactly @p size bytes, filled with a repeating ASCII sentence.
 */
inline std::vector<std::byte> makeCompressible(size_t size)
{
	static const char text[] = "Asset streaming runtime round-trip. ";
	const size_t textLength = sizeof(text) - 1;
	std::vector<std::byte> bytes(size);
	for (size_t index = 0; index < size; ++index)
		bytes[index] = static_cast<std::byte>(text[index % textLength]);
	return bytes;
}

/**
 * @brief Reads a device until it stops producing bytes.
 * @param device Device to drain; its position advances.
 * @param granularity Number of bytes requested per read call.
 * @return All bytes the device produced, concatenated.
 * @note This is the correct way to read a decompressing proxy: its `size()` reports the
 *       *compressed* size, so the loop must run until a read returns nothing.
 */
inline std::vector<std::byte> readToEnd(Elv::Io::Device& device, size_t granularity = 4096)
{
	std::vector<std::byte> output;
	std::vector<std::byte> buffer(granularity);
	for (;;) {
		const size_t got = device.read(buffer.data(), 1, buffer.size());
		if (got == 0)
			break;
		output.insert(output.end(), buffer.begin(), buffer.begin() + got);
	}
	return output;
}

}
#endif // UNITTESTS_TESTSUPPORT_HPP
